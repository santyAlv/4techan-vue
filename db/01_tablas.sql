-- Perfil público de cada cuenta (1 a 1 con auth.users). El foro es anónimo: solo se muestra el alias.
create table public.profiles (
  id           uuid primary key references auth.users (id) on delete cascade,
  alias        text not null unique
               check (alias ~ '^[A-Za-z0-9_]{3,20}$'),
  anio         smallint not null check (anio between 1 and 7),
  especialidad text check (especialidad is null or char_length(especialidad) between 3 and 40),
  rol          text not null default 'estudiante'
               check (rol in ('estudiante', 'moderador', 'admin')),
  ban_hasta    timestamptz,                       -- mientras sea futuro, la cuenta no puede publicar
  es_simulado  boolean not null default false,    -- dato de prueba
  created_at   timestamptz not null default now(),
  -- 1° a 3° no tienen especialidad; 4° a 7° sí (variable "año que cursa" de la Etapa 4)
  check (anio >= 4 or especialidad is null)
);

-- Tablones: /prog/, /taller/, /compraventa/, /eventos/, /consultas/
create table public.boards (
  id          smallint generated by default as identity primary key,
  slug        text not null unique check (slug ~ '^[a-z]{3,20}$'),
  nombre      text not null,
  descripcion text not null,
  activo      boolean not null default true
);

-- Publicaciones. No se borran físicamente: estado 'borrado' conserva el historial.
create table public.posts (
  id          bigint generated by default as identity primary key,
  board_id    smallint not null references public.boards (id),
  author_id   uuid not null references public.profiles (id),
  autor_alias text not null,                      -- copia del alias, para mostrarlo sin exponer perfiles
  titulo      text not null check (char_length(titulo) between 5 and 120),
  cuerpo      text not null check (char_length(cuerpo) between 5 and 4000),
  estado      text not null default 'publicado' check (estado in ('publicado', 'borrado')),
  borrado_por text check (borrado_por in ('autor', 'moderacion')),
  es_simulado boolean not null default false,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  check ((estado = 'publicado' and borrado_por is null)
      or (estado = 'borrado'   and borrado_por is not null))
);
create index posts_board_created_idx on public.posts (board_id, created_at desc);
create index posts_author_idx        on public.posts (author_id);

create table public.comments (
  id          bigint generated by default as identity primary key,
  post_id     bigint not null references public.posts (id),
  author_id   uuid not null references public.profiles (id),
  autor_alias text not null,
  cuerpo      text not null check (char_length(cuerpo) between 2 and 1000),
  estado      text not null default 'publicado' check (estado in ('publicado', 'borrado')),
  es_simulado boolean not null default false,
  created_at  timestamptz not null default now()
);
create index comments_post_idx on public.comments (post_id, created_at);

-- Reportes de publicaciones. Un estudiante reporta una publicación una sola vez.
create table public.reports (
  id          bigint generated by default as identity primary key,
  post_id     bigint not null references public.posts (id),
  reporter_id uuid not null references public.profiles (id),
  motivo      text not null
              check (motivo in ('spam', 'acoso', 'contenido_inapropiado', 'compraventa_prohibida', 'otro')),
  detalle     text check (detalle is null or char_length(detalle) <= 500),
  estado      text not null default 'pendiente' check (estado in ('pendiente', 'resuelto')),
  es_simulado boolean not null default false,
  created_at  timestamptz not null default now(),
  unique (post_id, reporter_id),
  check (motivo <> 'otro' or char_length(coalesce(detalle, '')) >= 10)
);
create index reports_estado_idx on public.reports (estado, created_at);

-- Resoluciones de la Comisión de Normas y Convivencia (historial de moderación).
create table public.resolutions (
  id           bigint generated by default as identity primary key,
  report_id    bigint not null unique references public.reports (id),
  moderator_id uuid not null references public.profiles (id),
  resultado    text not null
               check (resultado in ('descartado', 'post_borrado', 'borrado_ban_3d', 'derivado_asesor')),
  nota         text check (nota is null or char_length(nota) <= 500),
  es_simulado  boolean not null default false,
  created_at   timestamptz not null default now()
);

-- Apelaciones: sin fila = "sin apelar".
create table public.appeals (
  id            bigint generated by default as identity primary key,
  resolution_id bigint not null unique references public.resolutions (id),
  apelante_id   uuid not null references public.profiles (id),
  texto         text not null check (char_length(texto) between 10 and 500),
  estado        text not null default 'pendiente' check (estado in ('pendiente', 'mantenida', 'revertida')),
  resuelta_por  uuid references public.profiles (id),
  es_simulado   boolean not null default false,
  created_at    timestamptz not null default now(),
  resolved_at   timestamptz,
  check ((estado = 'pendiente' and resolved_at is null and resuelta_por is null)
      or (estado <> 'pendiente' and resolved_at is not null and resuelta_por is not null))
);

